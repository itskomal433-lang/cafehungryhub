  "pizza" | "burgers" | "momos" | "chinese" | "pasta" | "wraps" | "sides" | "drinks" | "desserts";

export type PriceOption = {
  /** Size / variant label, e.g. "Regular", "Gravy", "Medium". Empty for single-price items. */
  label: string;
  price: number;
};

export type MenuItem = {
  id: string;
  name: string;
  category: CategoryId;
  /** Menu section heading, e.g. "Simply Veg. 2". */
  group: string;
  description?: string | undefined;
  image: string;
  /** One entry for a fixed price, several for sizes / variants. */
  options: PriceOption[];
  /** Pizza items open the step-by-step builder. */
  pizza?: boolean | undefined;
  /** Optional extra choices with their own listed price (pizza combos). */
  addOns?: PriceOption[] | undefined;
  addOnLabel?: string | undefined;
  vegetarian: boolean;
  spicy?: boolean | undefined;
  bestseller?: boolean | undefined;
  isNew?: boolean | undefined;
  available: boolean;
};

